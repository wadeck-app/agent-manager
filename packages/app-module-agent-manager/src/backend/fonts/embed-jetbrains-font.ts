/**
 * Writes fontFiles.jetbrains.generated.ts: the latin woff2 files of JetBrains Mono (weights 400, 500, 700 and the italic 400) from the devDependency
 * `@fontsource/jetbrains-mono`, as base64, so the module bundle carries them (same reason as embed-fonts.ts: no asset folder, no data: font under the CSP).
 * Only the latin subset and the weights the session log renders are embedded, to keep the bundle small.
 *
 *   npm ci, then from packages/app-module-agent-manager:  npx tsx src/backend/fonts/embed-jetbrains-font.ts
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FILES = [
  { key: 'jetbrains-400', source: 'files/jetbrains-mono-latin-400-normal.woff2' },
  { key: 'jetbrains-500', source: 'files/jetbrains-mono-latin-500-normal.woff2' },
  { key: 'jetbrains-700', source: 'files/jetbrains-mono-latin-700-normal.woff2' },
  { key: 'jetbrains-400-italic', source: 'files/jetbrains-mono-latin-400-italic.woff2' },
] as const;

let pkgJson: string;
try {
  pkgJson = createRequire(import.meta.url).resolve('@fontsource/jetbrains-mono/package.json');
} catch {
  throw new Error('The devDependency @fontsource/jetbrains-mono is not installed. Run `npm ci` at the repository root, then run this script again.');
}
const folder = path.dirname(pkgJson);
const pkg = JSON.parse(fs.readFileSync(pkgJson, 'utf8')) as { name: string; version: string };
const entries = FILES.map(({ key, source }) => {
  const bytes = fs.readFileSync(path.join(folder, source));
  return `  '${key}': { sha256: '${createHash('sha256').update(bytes).digest('hex')}', bytes: ${bytes.length}, base64: '${bytes.toString('base64')}' },`;
});
const out = [
  '// Generated by embed-jetbrains-font.ts from the npm package @fontsource/jetbrains-mono (SIL Open Font License 1.1, see src/backend/fonts/THIRD_PARTY_NOTICES.md). Do not edit.',
  `export const JETBRAINS_SOURCE = { package: '${pkg.name}', version: '${pkg.version}' } as const;`,
  '',
  'export const JETBRAINS_DATA = {',
  ...entries,
  '} as const;',
  '',
].join('\n');
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'fontFiles.jetbrains.generated.ts'), out);
process.stdout.write(`wrote ${entries.length} fonts from ${pkg.name} ${pkg.version}\n`);
