/**
 * Writes fontFiles.generated.ts: the woff2 files of the Geist package, as base64, so the module bundle carries them.
 * `app-core-cli package` ships only the backend bundle, the components bundle and one stylesheet (no asset folder, no data: font under the CSP), so the
 * backend serves the fonts from memory (fontRoutes.ts).
 *
 *   npm pack geist@1.9.2 (in an empty folder), extract it, then:
 *   npx tsx src/backend/fonts/embed-fonts.ts <folder of the extracted package>
 *
 * The `geist` package is not a dependency: it has a required peer `next` (npm would install next, sharp and their install scripts).
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FILES = [
  { key: 'geist', source: 'dist/fonts/geist-sans/Geist-Variable.woff2' },
  { key: 'geist-mono', source: 'dist/fonts/geist-mono/GeistMono-Variable.woff2' },
] as const;

const folder = process.argv[2];
if (folder === undefined) {
  throw new Error('Usage: tsx embed-fonts.ts <folder of the extracted geist package (npm pack geist@<version>)>');
}
const pkg = JSON.parse(fs.readFileSync(path.join(folder, 'package.json'), 'utf8')) as { name: string; version: string; license: string };
if (pkg.name !== 'geist') {
  throw new Error(`${folder} holds the package "${pkg.name}", not "geist". Extract the tarball of "npm pack geist@<version>" and pass that folder.`);
}
const entries = FILES.map(({ key, source }) => {
  const bytes = fs.readFileSync(path.join(folder, source));
  return `  '${key}': { sha256: '${createHash('sha256').update(bytes).digest('hex')}', bytes: ${bytes.length}, base64: '${bytes.toString('base64')}' },`;
});
const out = [
  '// Generated by embed-fonts.ts from the npm package geist (SIL Open Font License 1.1, see src/backend/fonts/THIRD_PARTY_NOTICES.md). Do not edit.',
  `export const FONT_SOURCE = { package: 'geist', version: '${pkg.version}' } as const;`,
  '',
  'export const FONT_DATA = {',
  ...entries,
  '} as const;',
  '',
].join('\n');
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'fontFiles.generated.ts'), out);
process.stdout.write(`wrote ${entries.length} fonts from geist ${pkg.version}\n`);
